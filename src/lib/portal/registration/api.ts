/**
 * What the registration's route handlers read from a request body (Phase 4b, B6). Pure: a handler parses with these and acts on the result, so the shape a request must have is held
 * in one place and tested without a server.
 *
 * Nothing here reads a supplier, an organisation, an account or an actor from the body: those come from the session, and a body that carries one is simply not read for it (a scan
 * holds the handlers to that). A body is parsed strictly. A field of the wrong type, a list past its bound or a key that is not the section's is a refusal, never a guess.
 */

import { LIMITS, type DraftSection } from "./faults";
import { EDITABLE_STEPS, isRegistrationStep, type CreditorInput, type DeclarationInput, type RegistrationStep } from "./types";
import { CREDITOR_FIELDS, DECLARATION_KINDS } from "./types";

export type Parsed<T> = { ok: true; value: T } | { ok: false; message: string };

const bad = <T>(message: string): Parsed<T> => ({ ok: false, message });
const isObject = (v: unknown): v is Record<string, unknown> => typeof v === "object" && v !== null && !Array.isArray(v);

/// The longest id a body names. Ids are generated by the server (cuid), or `new:<n>` for a row the page has just added.
/// A SHA-256, as hex.
const SHA256 = /^[0-9a-f]{64}$/;

const ID = /^(?:new:[A-Za-z0-9_-]{1,40}|[A-Za-z0-9_-]{8,40})$/;

function strings(o: Record<string, unknown>, keys: readonly string[]): Record<string, string> | null {
  const out: Record<string, string> = {};
  for (const k of keys) {
    const v = o[k];
    if (v == null) {
      out[k] = "";
      continue;
    }
    if (typeof v !== "string") return null;
    out[k] = v;
  }
  return out;
}

export interface SaveRequestBody {
  step: RegistrationStep;
  version: number;
  section: DraftSection;
  remove: string[];
  /// The supplier asked to go on: the response then carries the step's rules.
  next: boolean;
}

export function parseSaveBody(body: Record<string, unknown>): Parsed<SaveRequestBody> {
  const step = typeof body.step === "string" ? body.step : "";
  if (!isRegistrationStep(step) || !EDITABLE_STEPS.includes(step)) return bad("That step cannot be saved.");
  if (typeof body.version !== "number" || !Number.isInteger(body.version) || body.version < 0 || body.version > 1_000_000_000) return bad("The page did not say which draft version it showed. Reload.");
  const next = body.next === true;
  const section = body.section;
  const remove: string[] = [];
  if (body.remove != null) {
    if (!Array.isArray(body.remove) || body.remove.length > LIMITS.rows || !body.remove.every((x) => typeof x === "string" && ID.test(x))) return bad("What to remove is not a list of documents.");
    remove.push(...(body.remove as string[]));
  }
  if (step === "review") return { ok: true, value: { step, version: body.version, section: { step: "review" }, remove, next } };
  if (!isObject(section)) return bad("The section to save is missing.");

  if (step === "documents") {
    const rows = section.documents;
    if (!Array.isArray(rows) || rows.length > LIMITS.rows) return bad("The documents are not a list, or there are too many.");
    const out: Extract<DraftSection, { step: "documents" }>["documents"][number][] = [];
    for (const r of rows) {
      if (!isObject(r)) return bad("A document is not a record.");
      const s = strings(r, ["id", "typeId", "title", "reference", "issuingAuthority", "expiresOn", "ratePercent"]);
      if (!s || !ID.test(s.id) || !ID.test(s.typeId)) return bad("A document does not say which it is.");
      if (r.notApplicable != null && typeof r.notApplicable !== "boolean") return bad("A document does not say whether it applies.");
      out.push({ id: s.id, typeId: s.typeId, title: s.title, reference: s.reference, issuingAuthority: s.issuingAuthority, expiresOn: s.expiresOn, ratePercent: s.ratePercent, notApplicable: r.notApplicable === true });
    }
    if (new Set(out.map((r) => r.id)).size !== out.length) return bad("A document is listed twice.");
    return { ok: true, value: { step, version: body.version, section: { step, documents: out }, remove, next } };
  }

  if (step === "codes") {
    const rows = section.documents;
    if (!Array.isArray(rows) || rows.length > LIMITS.rows) return bad("The documents are not a list, or there are too many.");
    const out: { id: string; valueIds: string[] }[] = [];
    for (const r of rows) {
      if (!isObject(r) || typeof r.id !== "string" || !ID.test(r.id) || r.id.startsWith("new:")) return bad("A document does not say which it is.");
      if (!Array.isArray(r.valueIds) || r.valueIds.length > LIMITS.valuesPerDocument || !r.valueIds.every((x) => typeof x === "string" && ID.test(x))) return bad("The codes of a document are not a list.");
      out.push({ id: r.id, valueIds: r.valueIds as string[] });
    }
    return { ok: true, value: { step, version: body.version, section: { step, documents: out }, remove, next } };
  }

  // epayment (the only step left: `step` is narrowed to the editable ones above)
  if (step !== "epayment") return bad("That step cannot be saved.");
  const creditorIn = section.creditor;
  if (creditorIn != null && !isObject(creditorIn)) return bad("The bank details are not a record.");
  const creditor: Partial<CreditorInput> = {};
  for (const k of CREDITOR_FIELDS) {
    const v = creditorIn?.[k];
    if (v == null) continue;
    if (typeof v !== "string") return bad("A bank detail is not text.");
    creditor[k] = v;
  }
  const text = (k: string): string | undefined | null => {
    const v = section[k];
    return v == null ? undefined : typeof v === "string" ? v : null;
  };
  const signatoryName = text("signatoryName");
  const signatoryDesignation = text("signatoryDesignation");
  if (signatoryName === null || signatoryDesignation === null) return bad("The signatory is not text.");
  if (section.giroConfirmed != null && typeof section.giroConfirmed !== "boolean") return bad("The tick is not yes or no.");
  // A tick is about the wording it was made on: it says which, by the hash of what the page showed.
  if (section.giroTextSha256 != null && (typeof section.giroTextSha256 !== "string" || !SHA256.test(section.giroTextSha256))) return bad("The wording the tick was made on is not named properly.");
  if (section.giroConfirmed === true && section.giroTextSha256 == null) return bad("The tick does not say which wording it was made on.");
  return {
    ok: true,
    value: {
      step,
      version: body.version,
      section: { step, creditor, ...(signatoryName !== undefined ? { signatoryName } : {}), ...(signatoryDesignation !== undefined ? { signatoryDesignation } : {}), ...(typeof section.giroConfirmed === "boolean" ? { giroConfirmed: section.giroConfirmed } : {}), ...(typeof section.giroTextSha256 === "string" ? { giroTextSha256: section.giroTextSha256 } : {}) },
      remove,
      next,
    },
  };
}

export interface SubmitRequestBody {
  version: number;
  password: string;
  declarations: DeclarationInput[];
}

export function parseSubmitBody(body: Record<string, unknown>): Parsed<SubmitRequestBody> {
  if (typeof body.version !== "number" || !Number.isInteger(body.version) || body.version < 0 || body.version > 1_000_000_000) return bad("The page did not say which draft version it showed. Reload.");
  if (typeof body.password !== "string") return bad("Enter your password to send the registration.");
  if (!Array.isArray(body.declarations) || body.declarations.length > DECLARATION_KINDS.length) return bad("The declarations are not a list.");
  const declarations: DeclarationInput[] = [];
  for (const d of body.declarations) {
    if (!isObject(d)) return bad("A declaration is not a record.");
    const kind = typeof d.kind === "string" && (DECLARATION_KINDS as readonly string[]).includes(d.kind) ? (d.kind as DeclarationInput["kind"]) : null;
    if (!kind) return bad("A declaration does not say which it is.");
    const s = strings(d, ["textVersionId", "textSha256", "signatoryName", "signatoryDesignation"]);
    if (!s || !SHA256.test(s.textSha256) || s.textVersionId.length > 60 || s.signatoryName.length > LIMITS.signatoryName * 2 || s.signatoryDesignation.length > LIMITS.signatoryDesignation * 2) return bad("A declaration is not in the form expected.");
    if (typeof d.confirmed !== "boolean") return bad("A declaration does not say whether it was ticked.");
    declarations.push({ kind, textVersionId: s.textVersionId, textSha256: s.textSha256, signatoryName: s.signatoryName, signatoryDesignation: s.signatoryDesignation, confirmed: d.confirmed });
  }
  return { ok: true, value: { version: body.version, password: body.password, declarations } };
}

export interface WithdrawRequestBody {
  version: number;
  versionId: string;
}

export function parseWithdrawBody(body: Record<string, unknown>): Parsed<WithdrawRequestBody> {
  if (typeof body.version !== "number" || !Number.isInteger(body.version) || body.version < 0 || body.version > 1_000_000_000) return bad("The page did not say which draft version it showed. Reload.");
  if (typeof body.versionId !== "string" || !ID.test(body.versionId)) return bad("The file is not named.");
  return { ok: true, value: { version: body.version, versionId: body.versionId } };
}

/// The query of a code search: which body and kind, the text typed, and a page's worth only.
export interface ValuesQuery {
  bodyId: string;
  kind: string | null;
  q: string;
}

export const VALUES_PAGE = 30;
export const VALUES_MIN_CHARS = 2;
export const VALUES_MAX_QUERY = 80;

export function parseValuesQuery(params: URLSearchParams): Parsed<ValuesQuery> {
  const bodyId = params.get("body") ?? "";
  if (!ID.test(bodyId) || bodyId.startsWith("new:")) return bad("Say which list to search.");
  const kind = params.get("kind");
  const q = (params.get("q") ?? "").trim().slice(0, VALUES_MAX_QUERY);
  return { ok: true, value: { bodyId, kind: kind && /^[A-Z_]{3,20}$/.test(kind) ? kind : null, q } };
}
